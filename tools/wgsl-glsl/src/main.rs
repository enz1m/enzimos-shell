//! Translates pinned framework material WGSL to compositor GLSL ES 3.0.
//!
//! Usage: enzui-wgsl-glsl <wgpu shader dir> <out header>.
//! ENCODED is enabled because compositor framebuffers contain sRGB-encoded values.

use naga::back::glsl;
use std::fmt::Write as _;

#[allow(clippy::iter_over_hash_type, reason = "Reflected bindings are sorted and deduplicated before generating output.")]
fn main() {
    let args: Vec<String> = std::env::args().collect();
    let [_, dir, out] = args.as_slice() else {
        eprintln!("usage: enzui-wgsl-glsl <wgpu shader dir> <out header>");
        std::process::exit(2);
    };
    let programs = [
        ("material", "material.wgsl", "vs_region", "fs_material"),
        ("probe", "material.wgsl", "vs_probe", "fs_probe"),
        ("filter", "material_filter.wgsl", "vs_fullscreen", "fs_filter"),
    ];
    let mut header = String::from("// Generated by tools/wgsl-glsl from the framework's iced_wgpu shaders; do not edit.\n#pragma once\n\nnamespace EnzMaterialShaders {\n\n");
    header.push_str("struct Binding {\n    const char* name;\n    unsigned binding;\n};\nstruct Program {\n    const char* vertex;\n    const char* fragment;\n    Binding blocks[4];\n    unsigned blockCount;\n    Binding samplers[4];\n    unsigned samplerCount;\n};\n\n");
    for (name, file, vertex, fragment) in programs {
        let source = std::fs::read_to_string(format!("{dir}/{file}")).unwrap_or_else(|error| fail(&format!("{file}: {error}")));
        let source = if file == "material.wgsl" {
            compositor_corners(source)
        } else {
            source
        };
        let source = format!("const ENCODED: bool = true;\n{source}");
        let module = naga::front::wgsl::parse_str(&source).unwrap_or_else(|error| fail(&error.emit_to_string(&source)));
        let info = naga::valid::Validator::new(naga::valid::ValidationFlags::all(), naga::valid::Capabilities::all())
            .validate(&module)
            .unwrap_or_else(|error| fail(&format!("{file}: {error:?}")));
        let mut blocks = Vec::new();
        let mut samplers = Vec::new();
        let mut stages = Vec::new();
        for (stage, entry) in [(naga::ShaderStage::Vertex, vertex), (naga::ShaderStage::Fragment, fragment)] {
            let options = glsl::Options {
                version: glsl::Version::Embedded { version: 300, is_webgl: false },
                writer_flags: glsl::WriterFlags::ADJUST_COORDINATE_SPACE,
                binding_map: Default::default(),
                zero_initialize_workgroup_memory: true,
            };
            let pipeline = glsl::PipelineOptions { shader_stage: stage, entry_point: entry.into(), multiview: None };
            let mut text = String::new();
            let reflection = glsl::Writer::new(&mut text, &module, &info, &options, &pipeline, naga::proc::BoundsCheckPolicies::default())
                .and_then(|mut writer| writer.write())
                .unwrap_or_else(|error| fail(&format!("{file} {entry}: {error:?}")));
            for (handle, uniform) in &reflection.uniforms {
                let binding = module.global_variables[*handle].binding.as_ref().map_or(0, |b| b.binding);
                blocks.push((uniform.clone(), binding));
            }
            for (sampler, mapping) in &reflection.texture_mapping {
                let binding = module.global_variables[mapping.texture].binding.as_ref().map_or(0, |b| b.binding);
                samplers.push((sampler.clone(), binding));
            }
            stages.push(text);
        }
        blocks.sort();
        blocks.dedup();
        samplers.sort();
        samplers.dedup();
        let list = |items: &[(String, u32)]| {
            let mut text = String::from("{");
            for (name, binding) in items {
                let _ = write!(text, "{{\"{name}\", {binding}}}, ");
            }
            text.push('}');
            text
        };
        let _ = write!(
            header,
            "inline const Program {name} = {{\nR\"glsl({})glsl\",\nR\"glsl({})glsl\",\n{}, {},\n{}, {},\n}};\n\n",
            stages[0],
            stages[1],
            list(&blocks),
            blocks.len(),
            list(&samplers),
            samplers.len()
        );
        if blocks.len() > 4 || samplers.len() > 4 {
            fail(&format!("{name}: more than four blocks or samplers"));
        }
    }
    header.push_str("} // namespace EnzMaterialShaders\n");
    std::fs::write(out, header).unwrap_or_else(|error| fail(&format!("{out}: {error}")));
}

fn compositor_corners(mut source: String) -> String {
    for (from, to) in [
        ("    policy: vec4<f32>,", "    policy: vec4<f32>,\n    corners: vec4<f32>,"),
        (
            "fn rounded_sdf(p: vec2<f32>, radius: f32) -> f32 {",
            "fn rounded_sdf(p: vec2<f32>, minimum: f32) -> f32 {
    let offset = p - u.region.xy;
    let left = select(u.corners.z, u.corners.x, offset.y < 0.0);
    let right = select(u.corners.w, u.corners.y, offset.y < 0.0);
    let radius = max(select(right, left, offset.x < 0.0), minimum);",
        ),
        ("return rounded_sdf(p, u.shape.x);", "return rounded_sdf(p, 0.0);"),
        ("min(max(u.shape.x, rim), short_half)", "min(rim, short_half)"),
    ] {
        if source.matches(from).count() != 1 {
            fail(&format!("material.wgsl: expected one occurrence of {from}"));
        }
        source = source.replace(from, to);
    }
    source
}

fn fail(message: &str) -> ! {
    eprintln!("enzui-wgsl-glsl: {message}");
    std::process::exit(1);
}
