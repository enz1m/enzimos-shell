#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn trace_labels_do_not_serialize_queries_errors_or_nested_messages() {
        for text in ["private query", "private query\nwith delimiters {,", "x"] {
            assert_eq!(Message::Search(text.into()).trace_kind(), "Search");
            assert_eq!(
                Message::PowerPolicy(text.into()).trace_kind(),
                "PowerPolicy"
            );
            assert_eq!(
                Message::DesktopsRead(1, Err(text.into())).trace_kind(),
                "DesktopsRead.Err"
            );
            assert_eq!(
                Message::PanelActionReady(1, Box::new(Message::Search(text.into()))).trace_kind(),
                "PanelActionReady"
            );
        }
    }
}
